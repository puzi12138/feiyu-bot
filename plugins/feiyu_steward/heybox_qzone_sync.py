    async def _hqz_detail_matches(self, qzone, tid, text_hash, image_count, *, automatic=False):
        def preflight():
            if _hqz_peak_paused(automatic):
                raise ValueError("peak_tariff")

        preflight()
        if (not isinstance(tid, str) or not re.fullmatch(r"[a-zA-Z0-9_-]{1,100}", tid)
                or type(image_count) is not int or not 0 <= image_count <= _MAX_SYNC_IMAGE_COUNT):
            return False
        detail = await self._hqz_detail(qzone, tid, automatic=automatic)
        if _hash_text(detail["content"]) != text_hash or not isinstance(detail.get("pic"), list):
            return False
        if "pictotal" in detail and _qzone_picture_count(detail["pictotal"]) != image_count:
            return False
        if image_count < 9:
            return len(detail["pic"]) == image_count
        # Nine pictures can itself be only a preview. Require a reported total,
        # a complete image response, and an ordered link to the verified detail.
        if _qzone_picture_count(detail.get("pictotal")) != image_count:
            return False
        preflight()
        ctx = await self._hqz_session_context(qzone)
        if str(ctx.uin) != BOT_QQ:
            raise ValueError("qzone_account_mismatch")
        images = await self._hqz_request(qzone, "GET", _QZONE_IMAGES_URL, params={
            "uin": BOT_QQ, "tid": tid, "g_tk": ctx.gtk2, "t1_source": 1, "r": random.random()},
            _preflight=preflight)
        # A read-only sample of this endpoint omitted code/identity entirely.
        # Validate these fields when present, and bind an otherwise anonymous
        # result to the requested detail through exact ordered preview refs.
        if "code" in images and (type(images["code"]) is not int or images["code"] != 0):
            return False
        if (("uin" in images and str(images["uin"]) != BOT_QQ)
                or ("tid" in images and str(images["tid"]) != tid)
                or ("pictotal" in images and _qzone_picture_count(images["pictotal"]) != image_count)):
            return False
        lists = [images[key] for key in ("pic", "imageUrls") if key in images]
        if not lists or any(not _qzone_image_lists_agree(detail["pic"], group, image_count) for group in lists):
            return False
        # Both response fields, when supplied, must describe the same sequence.
        return all(_qzone_image_refs(left) & _qzone_image_refs(right)
                   for group in lists[1:] for left, right in zip(lists[0], group))

    async def _hqz_publish(self, qzone, source, grant, *, transport, manual_backfill=False, last_automatic=None,
                           expected_origin=None):
        if _hqz_peak_paused(not manual_backfill):
            raise ValueError("peak_tariff")
        if not manual_backfill:
            scope = _hqz_resume_scope(self)
            stamp = _hqz_resume_source_time(self, source.get("source_created_at"))
            if stamp is None:
                raise ValueError("incident_resume_barrier")
            scope["source_created_at"] = stamp
        _check_sync_media_budget(source.get("media"))
        if not isinstance(source.get("id"), str) or not re.fullmatch(r"\d{5,20}", source["id"]):
            raise ValueError("source_id_invalid")
        if not manual_backfill and expected_origin not in {
                "ordinary", "scheduled_autopost", _DUAL_COMIC_ORIGIN, _OWNER_EXTRA_ORIGIN,
                _REPLACEMENT_ORIGIN, "owner_qzone"}:
            raise ValueError("source_origin_unresolved")
        if (not manual_backfill and expected_origin in {_REPLACEMENT_ORIGIN, _DUAL_COMIC_ORIGIN, _OWNER_EXTRA_ORIGIN}
                and self._hqz_source_origin(str(grant["heybox_uid"]), source["id"],
                                            media=source.get("media")) != expected_origin):
            raise ValueError("source_origin_unresolved")
        source_binding = _hqz_selection_hash(source)
        manual_extra = False
        if manual_backfill:
            operations = getattr(self, "_heybox_posts_ops", None)
            matches = [op for op in operations.values() if isinstance(op, dict)
                       and str(op.get("account_uid", "")) == str(grant["heybox_uid"])
                       and str(op.get("post_id", "")) == source["id"]] if isinstance(operations, dict) else []
            if any(op.get("publication_origin") == _OWNER_EXTRA_ORIGIN for op in matches):
                if self._hqz_source_origin(str(grant["heybox_uid"]), source["id"],
                                           media=source.get("media")) != _OWNER_EXTRA_ORIGIN:
                    raise ValueError("source_origin_unresolved")
                manual_extra = True
        current = qzone.service.publish_post
        if getattr(current, "_feiyu_qzone_guard_owner", None) is not self:
            raise ValueError("qzone_guard_unavailable")
        if str(await qzone.session.get_uin()) != BOT_QQ:
            raise ValueError("qzone_account_mismatch")
        module = importlib.import_module(qzone.qzone.__class__.__module__)
        original_request, original_normalize = qzone.qzone.request, module.normalize_images
        folder = self._hqz_root / "images"
        folder.mkdir(parents=True, exist_ok=True)
        if folder.is_symlink():
            raise ValueError("sync_image_storage_unavailable")
        paths = []
        for data in source["media"]:
            digest = hashlib.sha256(data).hexdigest()
            with Image.open(BytesIO(data)) as image:
                extension = {"PNG": "png", "JPEG": "jpg", "WEBP": "webp"}[image.format]
            target = folder / f"{digest}.{extension}"
            if target.is_symlink():
                raise ValueError("sync_image_storage_unavailable")
            if target.exists():
                if hashlib.sha256(target.read_bytes()).hexdigest() != digest:
                    raise ValueError("sync_image_storage_unavailable")
            else:
                tmp = folder / (uuid.uuid4().hex + ".tmp")
                try:
                    with tmp.open("xb") as output:
                        output.write(data)
                        output.flush()
                        os.fsync(output.fileno())
                    os.replace(tmp, target)
                finally:
                    tmp.unlink(missing_ok=True)
            paths.append(f"data/plugin_data/feiyu_steward/heybox-qzone-sync/images/{target.name}")

        reservation_key = _request_key(None, {"text": source["body"], "images": paths})

        async def checked_request(method, url, **kwargs):
            if _ROUTE.get() is not self:
                return await original_request(method, url, **kwargs)
            if _hqz_peak_paused(not manual_backfill):
                raise ValueError("peak_tariff")
            if str(getattr(transport, "expected_uid", "")) != str(grant["heybox_uid"]):
                raise ValueError("source_account_changed")
            client = await transport.client()

            def preflight():
                if _hqz_peak_paused(not manual_backfill):
                    raise ValueError("peak_tariff")
                if not manual_backfill:
                    scope = _hqz_resume_scope(self)
                    stamp = _hqz_resume_source_time(self, source.get("source_created_at"))
                    if stamp is None or scope.get("source_created_at") != stamp:
                        raise ValueError("incident_resume_barrier")
                runtime = getattr(getattr(transport, "plugin", None), "runtime", None)
                clients = getattr(runtime, "_clients", None)
                credentials = getattr(client, "credentials", None)
                if (not isinstance(clients, dict) or clients.get(("default", False)) is not client
                        or getattr(client, "closed", True)
                        or str(getattr(credentials, "uid", "")) != str(grant["heybox_uid"])):
                    raise ValueError("source_account_changed")
                if self._hqz_grant() != grant or _hqz_selection_hash(source) != source_binding:
                    raise ValueError("sync_authorization_or_policy_changed")
                local_id = source.get("local_operation_id")
                if local_id is not None:
                    operations = getattr(self, "_heybox_posts_ops", None)
                    local_op = operations.get(local_id) if isinstance(operations, dict) else None
                    if (not isinstance(local_op, dict) or local_op.get("id") != local_id
                            or str(local_op.get("account_uid", "")) != str(grant["heybox_uid"])
                            or str(local_op.get("post_id", "")) != source["id"]
                            or local_op.get("title") != source["title"] or local_op.get("text") != source["text"]):
                        raise ValueError("sync_authorization_or_policy_changed")
                if not manual_backfill and self._hqz_auto_block(
                        datetime.now(TZ), last_automatic, reservation_key=reservation_key,
                        expected_origin=expected_origin, uid=str(grant["heybox_uid"]),
                        identifier=source["id"], media=source.get("media")):
                    raise ValueError("sync_authorization_or_policy_changed")
                if manual_backfill and self._hqz_manual_extra_block(
                        str(grant["heybox_uid"]), source["id"], datetime.now(TZ), media=source.get("media")):
                    raise ValueError("sync_authorization_or_policy_changed")
                if not manual_backfill:
                    try:
                        current_origin = self._hqz_source_origin(str(grant["heybox_uid"]), source["id"],
                                                                 media=source.get("media"))
                    except (KeyError, ValueError):
                        raise ValueError("sync_authorization_or_policy_changed") from None
                    if current_origin != expected_origin:
                        raise ValueError("sync_authorization_or_policy_changed")
                else:
                    try:
                        declined = self._hqz_owner_sync_declined(str(grant["heybox_uid"]), source["id"],
                                                                 media=source.get("media"))
                    except ValueError:
                        raise ValueError("sync_authorization_or_policy_changed") from None
                    if declined:
                        raise ValueError("sync_authorization_or_policy_changed")

            preflight()
            return await self._hqz_request(qzone, method, url, _preflight=preflight, **kwargs)

        async def checked_normalize(images):
            if _ROUTE.get() is not self:
                return await original_normalize(images)
            if list(images or []) != paths:
                raise ValueError("sync_image_list_changed")
            # The exact, already validated bytes are used even if a path is
            # unavailable; the upstream normalizer otherwise silently drops it.
            return list(source["media"])

        qzone.qzone.request = checked_request
        module.normalize_images = checked_normalize
        token = _ROUTE.set(self)
        try:
            timeout = _hqz_publish_timeout(len(paths))
            if manual_extra:
                # The owner's exact-task capability is intentionally invalid
                # in child tasks; preserve it while retaining a bounded timeout.
                async with same_task_deadline(timeout):
                    return await current(text=source["body"], images=paths)
            return await asyncio.wait_for(current(text=source["body"], images=paths), timeout=timeout)
        finally:
            _ROUTE.reset(token)
            if qzone.qzone.request is checked_request:
                qzone.qzone.request = original_request
            if module.normalize_images is checked_normalize:
                module.normalize_images = original_normalize

    async def heybox_qzone_sync_once(self, *, backfill_id=None):
        # Scheduler work must not inherit the owner exception when it happens
        # to be spawned from an active owner request.  This also keeps the
        # process-wide provider and OneBot gates on the automatic path while
        # an upstream session waits for its own lock.
        try:
            if backfill_id is None:
                with automatic_scope():
                    result = await self._heybox_qzone_sync_once(backfill_id=backfill_id)
                self._hqz_record_failure(result)
                return result
            return await self._heybox_qzone_sync_once(backfill_id=backfill_id)
        except Exception as error:
            if backfill_id is None and _incident_exception_category(error) is not None:
                record_failure(getattr(self, "root", None), "heybox_qzone_sync", "qzone_sync_once", error=error)
            if backfill_id is None and _hqz_storage_fault(error):
                if isinstance(error, _HqzStorageFailure):
                    self._hqz_record_failure(_hqz_exception_result(error))
                    raise
                failure = _HqzStorageFailure(_hqz_error_class(error))
                self._hqz_record_failure(_hqz_exception_result(failure))
                raise failure from None
            result = _hqz_exception_result(error)
            if backfill_id is None:
                self._hqz_record_failure(result)
            return result

    async def _heybox_qzone_sync_once(self, *, backfill_id=None):
        async with self._hqz_lock:
            grant = self._hqz_grant()
            if not grant:
                return {"ok": False, "reason": "sync_not_authorized"}
            manual_backfill = backfill_id is not None
            if not manual_backfill:
                try:
                    resume_scope = _hqz_resume_scope(self)
                except ValueError as error:
                    return {"ok": True, "reason": _hqz_known_value(error)}
                automatic_cutoff = max(grant["auto_start_at_epoch"],
                                       math.floor(resume_scope["snapshot"][0]))
            if manual_backfill and (not isinstance(backfill_id, str) or backfill_id not in grant["backfill_ids"]):
                return {"ok": False, "reason": "backfill_not_authorized"}
            if not manual_backfill and not grant["auto_sync"]:
                return {"ok": False, "reason": "auto_sync_disabled"}
            if not manual_backfill and not self._hqz_auto_grant_valid(grant):
                return {"ok": False, "reason": "auto_baseline_unavailable"}
            qzone = self.plugin("astrbot_plugin_qzone")
            if qzone is None or getattr(qzone.service.publish_post, "_feiyu_qzone_guard_owner", None) is not self:
                return {"ok": False, "reason": "qzone_guard_unavailable"}
            sending_reserved = False
            try:
                if _hqz_peak_paused(not manual_backfill):
                    # Keep unresolved receipts unchanged for an off-peak readback.
                    return {"ok": True, "reason": "peak_tariff"}
                if not manual_backfill and not self._hqz_session_route_ready(qzone):
                    return {"ok": True, "reason": "qzone_session_waiting"}
                transport = self._post_transport()
                source_rows = await self._hqz_source_list(grant, transport, automatic=not manual_backfill)
                feed = await self._hqz_own_feed(qzone, automatic=not manual_backfill)
                with closing(self._hqz_db()) as db:
                    pending = list(db.execute("SELECT source_uid,source_id,text_hash,image_count,tid FROM receipts "
                                              "WHERE status IN ('sending','unknown','sent_unverified')"))
                    for uid, identifier, expected, image_count, tid in pending:
                        # Without a platform receipt, even a matching post may
                        # have come from another path; keep the attempt unknown.
                        matches = [p for p in feed if tid and str(p.get("tid")) == tid]
                        if len(matches) == 1 and await self._hqz_detail_matches(
                                qzone, tid, expected, image_count, automatic=not manual_backfill):
                            db.execute("UPDATE receipts SET status='readback_matched',tid=?,updated=? "
                                       "WHERE source_uid=? AND source_id=?", (str(matches[0]['tid']), time.time(), uid, identifier))
                    db.commit()
                    if db.execute("SELECT 1 FROM receipts WHERE status IN ('sending','unknown','sent_unverified') LIMIT 1").fetchone():
                        return {"ok": False, "reason": "sync_result_unresolved"}
                    now_local = datetime.now(TZ)
                    last_automatic = db.execute("SELECT MAX(attempted) FROM automatic_attempts").fetchone()[0]
                    block = "daily_limit" if not qzone_publication_usage(self.state, now_local)["remaining"] else ""
                    if block:
                        return {"ok": False, "reason": "publication_policy_blocked", "policy": block}
                    if not manual_backfill:
                        # Older ordinary sources can be incomplete or exceed
                        # media budgets. Do not let them starve a proven slot
                        # or a bound explicit owner sync request. Global Qzone
                        # unresolved receipts have already stopped this check.
                        def source_priority(item):
                            try:
                                origin = self._hqz_source_origin(str(grant["heybox_uid"]), item[0])
                                if origin == _OWNER_EXTRA_ORIGIN:
                                    return -1  # Its owner approval has a short lifetime.
                                return 0 if origin in {"scheduled_autopost", _DUAL_COMIC_ORIGIN,
                                                       _REPLACEMENT_ORIGIN, "owner_qzone"} else 1
                            except ValueError:
                                return 1
                        source_rows = sorted(source_rows, key=source_priority)
                    selection_pending = False
                    selection_calls_remaining = _MAX_SELECTION_CALLS_PER_CHECK
                    for identifier, row in source_rows:
                        if manual_backfill and identifier != backfill_id:
                            continue
                        if not manual_backfill and identifier in grant["baseline_source_ids"]:
                            continue
                        if not manual_backfill:
                            resume_scope = _hqz_resume_scope(self)
                            resume_scope["source_created_at"] = None
                            stamp = _hqz_resume_source_time(self, row.get("create_at"))
                            if stamp is None or stamp <= automatic_cutoff:
                                continue
                        uid = str(grant["heybox_uid"])
                        receipt = db.execute("SELECT status,tid,image_count FROM receipts WHERE source_uid=? AND source_id=?", (uid, identifier)).fetchone()
                        if receipt:
                            if manual_backfill:
                                return {"ok": receipt[0] == "readback_matched", "status": receipt[0],
                                        "source_id": identifier, "tid": receipt[1],
                                        "media_verified": False, "needs_media_review": bool(receipt[2])}
                            continue
                        if manual_backfill and self._hqz_owner_sync_declined(uid, identifier):
                            return {"ok": False, "reason": "owner_sync_declined", "source_id": identifier}
                        if manual_backfill:
                            block = self._hqz_manual_extra_block(uid, identifier, datetime.now(TZ))
                            if block:
                                return {"ok": False, "reason": "publication_policy_blocked", "policy": block}
                        # Proven slots and bound explicit owner requests are
                        # already authorized for both platforms. Other sources
                        # get a public-text decision; old skips are not re-read.
                        origin, selection = None, None
                        if not manual_backfill:
                            origin = self._hqz_source_origin(uid, identifier)
                            if origin in {"owner_no_qzone", "superseded_for_chinese_replacement"}:
                                continue
                            if (origin == _DUAL_COMIC_ORIGIN
                                    and not self._hqz_comic_automatic_enabled(grant)):
                                continue
                            block = self._hqz_auto_block(datetime.now(TZ), last_automatic,
                                expected_origin=origin, uid=uid, identifier=identifier)
                            if block:
                                return {"ok": False, "reason": "publication_policy_blocked", "policy": block}
                            if origin not in {"scheduled_autopost", _DUAL_COMIC_ORIGIN, _OWNER_EXTRA_ORIGIN, _REPLACEMENT_ORIGIN, "owner_qzone"}:
                                selection = self._hqz_selection_row(db, uid, identifier)
                                if selection and selection["status"] == "skipped":
                                    continue
                                if (selection and selection["status"] == "retry"
                                        and time.time() < selection["retry_at"]):
                                    selection_pending = True
                                    continue
                                if ((selection is None or selection["status"] == "retry")
                                        and selection_calls_remaining == 0):
                                    selection_pending = True
                                    continue
                        try:
                            source = await self._hqz_source_post(grant, transport, identifier, row,
                                require_after=None if manual_backfill else automatic_cutoff,
                                automatic=not manual_backfill)
                        except ValueError as error:
                            if manual_backfill or str(error) != "source_video_unsupported":
                                raise
                            if self._hqz_grant() != grant:
                                return {"ok": False, "reason": "sync_authorization_changed"}
                            now = time.time()
                            db.execute("INSERT OR IGNORE INTO receipts VALUES (?,?,?,?,?,?,?,?,?,?)", (
                                uid, identifier, BOT_QQ, grant["grant_id"], "unsupported_video", "", 0, None, now, now))
                            db.commit()
                            continue
                        if manual_backfill and self._hqz_owner_sync_declined(uid, identifier, media=source.get("media")):
                            return {"ok": False, "reason": "owner_sync_declined", "source_id": identifier}
                        if manual_backfill:
                            block = self._hqz_manual_extra_block(uid, identifier, datetime.now(TZ), media=source.get("media"))
                            if block:
                                return {"ok": False, "reason": "publication_policy_blocked", "policy": block}
                        if not manual_backfill and origin not in {"scheduled_autopost", _DUAL_COMIC_ORIGIN, _OWNER_EXTRA_ORIGIN, _REPLACEMENT_ORIGIN, "owner_qzone"}:
                            current_hash = _hqz_selection_hash(source)
                            needs_classifier = (selection is None or selection["status"] == "retry"
                                                or selection["content_hash"] != current_hash)
                            if needs_classifier:
                                if selection_calls_remaining == 0:
                                    selection_pending = True
                                    continue
                                selection_calls_remaining -= 1
                            selected = await self._hqz_select_source(db, grant, source, selection)
                            if selected == "retry":
                                selection_pending = True
                                continue
                            if selected == "skipped":
                                continue
                            # A classifier may take time. Re-read the public
                            # source and never apply its decision to new text;
                            # release old media before acquiring it again.
                            selected_hash = _hqz_selection_hash(source)
                            del source
                            source = await self._hqz_source_post(
                                grant, transport, identifier, row, require_after=automatic_cutoff,
                                automatic=True)
                            if _hqz_selection_hash(source) != selected_hash:
                                return {"ok": False, "reason": "source_selection_changed"}
                        incomplete = [post for post in feed if post.get("has_more_con") != 0]
                        if len(incomplete) > _MAX_DETAIL_CHECKS:
                            raise ValueError("qzone_detail_check_limit")
                        for post in incomplete:
                            if _hqz_peak_paused(not manual_backfill):
                                return {"ok": True, "reason": "peak_tariff"}
                            post["content"] = (await self._hqz_detail(
                                qzone, str(post["tid"]), automatic=not manual_backfill))["content"]
                            post["has_more_con"] = 0
                        matches = [p for p in feed if source["url"] in str(p.get("content", ""))
                                   or (source["title"] and source["title"] in str(p.get("content", "")))
                                   or (source["text"] and source["text"] in str(p.get("content", "")))
                                   or _normal(source["body"]) == _normal(str(p.get("content", "")))]
                        if matches:
                            # Text and image count cannot prove media identity.
                            # Retain the uncertainty even if the post later
                            # disappears from the feed; never auto-republish it.
                            if self._hqz_grant() != grant:
                                return {"ok": False, "reason": "sync_authorization_changed"}
                            now = time.time()
                            db.execute("INSERT OR IGNORE INTO receipts VALUES (?,?,?,?,?,?,?,?,?,?)", (
                                uid, identifier, BOT_QQ, grant["grant_id"], "possible_existing", _hash_text(source["body"]),
                                len(source["media"]), str(matches[0]["tid"]) if len(matches) == 1 else None, now, now))
                            db.commit()
                            return {"ok": False, "reason": "possible_existing_post", "source_id": identifier}
                        # Re-check the grant after every awaited read and before
                        # the durable reservation or any public operation.
                        if self._hqz_grant() != grant:
                            return {"ok": False, "reason": "sync_authorization_changed"}
                        if _hqz_peak_paused(not manual_backfill):
                            return {"ok": True, "reason": "peak_tariff"}
                        if not manual_backfill:
                            if self._hqz_source_origin(uid, identifier, media=source.get("media")) != origin:
                                return {"ok": False, "reason": "source_origin_changed"}
                            if (origin == _DUAL_COMIC_ORIGIN
                                    and not self._hqz_comic_automatic_enabled(self._hqz_grant())):
                                return {"ok": True, "reason": "comic_automatic_paused"}
                            block = self._hqz_auto_block(datetime.now(TZ), last_automatic,
                                expected_origin=origin, uid=uid, identifier=identifier, media=source.get("media"))
                            if block:
                                return {"ok": False, "reason": "publication_policy_blocked", "policy": block}
                        now = time.time()
                        if not manual_backfill:
                            resume_scope = _hqz_resume_scope(self)
                            stamp = _hqz_resume_source_time(self, source.get("source_created_at"))
                            if stamp is None:
                                return {"ok": True, "reason": "incident_resume_barrier"}
                            resume_scope["source_created_at"] = stamp
                        try:
                            db.execute("INSERT INTO receipts VALUES (?,?,?,?,?,?,?,?,?,?)", (
                                uid, identifier, BOT_QQ, grant["grant_id"], "sending", _hash_text(source["body"]),
                                len(source["media"]), None, now, now))
                            if not manual_backfill and origin != _OWNER_EXTRA_ORIGIN:
                                db.execute("INSERT INTO automatic_attempts VALUES (?,?,?)", (uid, identifier, now))
                            db.commit()
                            sending_reserved = True
                        except sqlite3.IntegrityError:
                            return {"ok": False, "reason": "sync_already_claimed"}
                        try:
                            published = await self._hqz_publish(qzone, source, grant, transport=transport, manual_backfill=manual_backfill,
                                                                last_automatic=last_automatic, expected_origin=origin)
                            tid = str(getattr(published, "tid", "") or "")
                            if not tid:
                                raise ValueError("qzone_receipt_missing")
                            db.execute("UPDATE receipts SET status='sent_unverified',tid=?,updated=? "
                                       "WHERE source_uid=? AND source_id=?", (tid, time.time(), uid, identifier))
                            db.commit()
                            if _hqz_peak_paused(not manual_backfill):
                                return {"ok": True, "status": "sent_unverified", "source_id": identifier,
                                        "tid": tid, "reason": "peak_tariff"}
                            recent = await self._hqz_own_feed(qzone, automatic=not manual_backfill)
                            matches = [p for p in recent if str(p.get("tid")) == tid]
                            if len(matches) == 1 and await self._hqz_detail_matches(
                                    qzone, tid, _hash_text(source["body"]), len(source["media"]),
                                    automatic=not manual_backfill):
                                db.execute("UPDATE receipts SET status='readback_matched',updated=? "
                                           "WHERE source_uid=? AND source_id=?", (time.time(), uid, identifier))
                                db.commit()
                                return {"ok": True, "status": "readback_matched", "source_id": identifier, "tid": tid,
                                        "media_verified": False, "needs_media_review": bool(source["media"])}
                            return {"ok": False, "reason": "sync_readback_unconfirmed", "source_id": identifier}
                        except BaseException:
                            db.execute("UPDATE receipts SET status='unknown',updated=? "
                                       "WHERE source_uid=? AND source_id=? AND status='sending'", (time.time(), uid, identifier))
                            db.commit()
                            raise
                    if manual_backfill and not any(identifier == backfill_id for identifier, _ in source_rows):
                        return {"ok": False, "reason": "source_post_unavailable", "source_id": backfill_id}
                    if selection_pending:
                        return {"ok": False, "reason": "selection_pending"}
                    unsupported = db.execute("SELECT COUNT(*) FROM receipts WHERE status='unsupported_video'").fetchone()[0]
                    return {"ok": True, "status": "up_to_date", "unsupported_video": unsupported}
            except Exception as error:
                # Only local reason codes are returned; upstream exceptions may
                # contain credentials, post contents, or raw response bodies.
                if (not manual_backfill and _incident_exception_category(error) is not None
                        and _hqz_known_value(error) not in {"incident_barrier_unavailable", "incident_resume_barrier"}):
                    record_failure(getattr(self, "root", None), "heybox_qzone_sync", "qzone_sync_once", error=error)
                if sending_reserved:
                    # The inner handler retains unknown or sent_unverified.
                    # Report that uncertainty without retrying the write.
                    return {"ok": False, "reason": "sync_readback_unconfirmed"}
                if not manual_backfill and _hqz_storage_fault(error):
                    raise _HqzStorageFailure(_hqz_error_class(error)) from None
                return _hqz_exception_result(error)

    async def heybox_qzone_sync_monitor(self):
        while not self._hqz_stopped:
            try:
                result = await self.heybox_qzone_sync_once()
            except Exception as error:
                result = _hqz_exception_result(error)
            self._hqz_record_check(result)
            await asyncio.sleep(300)
