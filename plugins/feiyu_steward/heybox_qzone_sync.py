def _check_sync_media_budget(media):
    if not isinstance(media, list) or len(media) > _MAX_SYNC_IMAGE_COUNT:
        raise ValueError("source_image_budget_exceeded")
    total = 0
    for data in media:
        if not isinstance(data, bytes) or not 0 < len(data) <= _MAX_IMAGE:
            raise ValueError("source_image_invalid")
        total += len(data)
        if total > _MAX_SYNC_IMAGE_BYTES:
            raise ValueError("source_image_budget_exceeded")


def _hqz_source_cards_match(cards, expected):
    """Match normal cards or the observed older editor's display metadata.

    The older representation has string display sizes and checked=false on
    every image. Those sizes are presentation data, not the uploaded pixels;
    the original dimensions are verified against the local upload list below.
    """
    if _cards_readback_matches(cards, expected):
        return True
    if (not isinstance(cards, list) or not isinstance(expected, list)
            or len(cards) != len(expected) or len(cards) < 2):
        return False
    text_card = cards[0]
    if (isinstance(text_card, dict) and set(text_card) == {"type", "text", "checked"}
            and text_card.get("checked") is False):
        # Reuse the existing exact/key and narrowly scoped attribution checks.
        text_card = {"type": text_card["type"], "text": text_card["text"]}
    if not _cards_readback_matches([text_card], expected[:1]):
        return False
    # A checked text card can accompany otherwise normal image cards.
    if _cards_readback_matches(cards[1:], expected[1:]):
        return True
    for current, wanted in zip(cards[1:], expected[1:]):
        if (not isinstance(current, dict) or not isinstance(wanted, dict)
                or set(current) != {"type", "url", "width", "height", "checked"}
                or set(wanted) != {"type", "url", "width", "height"}
                or current.get("type") != "img" or wanted.get("type") != "img"
                or current.get("checked") is not False
                or not _image_url_matches(current.get("url"), wanted.get("url"))):
            return False
        for key in ("width", "height"):
            value = current[key]
            if not isinstance(value, str) or not re.fullmatch(r"[1-9]\d{0,3}", value) or int(value) > 8192:
                return False
    return True


def _hqz_unidentified_owner_write(operations, uid):
    """An unresolved owner write must not be adopted from the public list.

    This deliberately covers both the old immediate origin and the new
    replacement origin.  A missing post ID cannot be tied to a listed source,
    so the scheduler must fail closed instead of guessing which post it was.
    """
    return any(isinstance(op, dict) and str(op.get("account_uid", "")) == uid
               and op.get("publication_origin") in {"owner_immediate", _REPLACEMENT_ORIGIN, _OWNER_EXTRA_ORIGIN}
               and op.get("phase") in {"dispatching", "unknown"}
               and not re.fullmatch(r"\d{5,20}", str(op.get("post_id", "")))
               for op in operations.values())


