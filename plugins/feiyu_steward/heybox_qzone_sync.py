class _HqzStorageFailure(OSError):
    """A fixed, content-free signal for the incident hook."""

    def __init__(self, error_class):
        super().__init__("sync_storage_unavailable")
        self.error_class = error_class if error_class in _CHECK_ERROR_CLASSES else "other"


def _hqz_known_value(error):
    """Read a local fixed reason only for comparison with a whitelist."""
    if isinstance(error, ValueError) and len(error.args) == 1 and type(error.args[0]) is str:
        return error.args[0]
    return None


def _hqz_storage_fault(error):
    category = _incident_exception_category(error)
    if category is None:
        return False
    return category == "storage_failed" or _hqz_known_value(error) in _GENERAL_STORAGE_REASONS


def _hqz_error_class(error):
    """Return a fixed diagnostic label, never the exception name or text."""
    if isinstance(error, _HqzStorageFailure):
        return error.error_class if error.error_class in _CHECK_ERROR_CLASSES else "other"
    if isinstance(error, sqlite3.Error):
        return "sqlite"
    if isinstance(error, TimeoutError):
        return "timeout"
    if isinstance(error, ConnectionError):
        return "connection"
    bases = type(error).__mro__
    if any(base.__module__.startswith(("httpx", "httpcore", "aiohttp")) for base in bases):
        return "http_client"
    if any(base.__module__ == "data.plugins.astrbot_plugin_xiaoheihe_adapter.xiaoheihe.api_client"
           and base.__name__ == "XiaoheiheApiError" for base in bases):
        return "heybox_api"
    for cls, label in ((OSError, "os"), (TypeError, "type"), (AttributeError, "attribute"),
                       (KeyError, "key"), (ValueError, "value"), (RuntimeError, "runtime")):
        if isinstance(error, cls):
            return label
    return "other"


def _hqz_exception_result(error):
    """Distinguish known control pauses from failures using the incident policy."""
    if _incident_exception_category(error) is None:
        reason = "peak_tariff" if isinstance(error, PeakTariffPaused) else "automatic_action_paused"
        return {"ok": True, "reason": reason}
    known = _hqz_known_value(error)
    reason = known if known in _EXCEPTION_SKIP_REASONS or known in _EXCEPTION_FAILURE_REASONS else "sync_unavailable"
    result = {"ok": False, "reason": reason}
    if reason == "sync_unavailable":
        result["error_class"] = _hqz_error_class(error)
    return result


def _safe_check_record(result, checked_at):
    """Copy only fixed, non-content fields from an automatic check result."""
    result = result if isinstance(result, dict) else {}
    ok = result.get("ok") is True
    status_value, reason_value = result.get("status"), result.get("reason")
    # A protection pause skips the check and must not be reported as healthy.
    if ok and isinstance(reason_value, str) and reason_value in _CHECK_PAUSE_REASONS:
        ok = False
    status = status_value if ok and isinstance(status_value, str) and status_value in _CHECK_STATUSES else ""
    reason = reason_value if not ok and isinstance(reason_value, str) and reason_value in _CHECK_REASONS else ""
    if (ok and not status) or (not ok and not reason):
        ok, status, reason = False, "", "sync_unavailable"
    policy = result.get("policy") if reason == "publication_policy_blocked" else ""
    if not isinstance(policy, str) or policy not in _CHECK_POLICIES:
        policy = ""
    counts = {}
    unsupported = result.get("unsupported_video")
    if type(unsupported) is int and 0 <= unsupported <= 1_000_000_000:
        counts["unsupported_video"] = unsupported
    error_class = result.get("error_class")
    if reason != "sync_unavailable" or not isinstance(error_class, str) or error_class not in _CHECK_ERROR_CLASSES:
        error_class = ""
    return {"schema": 1, "checked_at_epoch": checked_at, "ok": ok, "status": status,
            "reason": reason, "policy": policy, "counts": counts, "error_class": error_class}


def _valid_check_record(record):
    base_fields = {"schema", "checked_at_epoch", "ok", "status", "reason", "policy", "counts"}
    if (not isinstance(record, dict) or set(record) not in (base_fields, base_fields | {"error_class"})
            or type(record["schema"]) is not int or record["schema"] != 1
            or type(record["checked_at_epoch"]) is not int or not 1_000_000_000 <= record["checked_at_epoch"] < 10_000_000_000
            or type(record["ok"]) is not bool or not isinstance(record["counts"], dict)
            or not all(isinstance(record[key], str) for key in ("status", "reason", "policy"))
            or set(record["counts"]) - {"unsupported_video"}):
        return False
    if any(type(value) is not int or not 0 <= value <= 1_000_000_000
           for value in record["counts"].values()):
        return False
    if "error_class" in record:
        error_class = record["error_class"]
        if (not isinstance(error_class, str)
                or (error_class and (error_class not in _CHECK_ERROR_CLASSES or record["reason"] != "sync_unavailable"))):
            return False
    if record["ok"]:
        return record["status"] in _CHECK_STATUSES and record["reason"] == "" and record["policy"] == ""
    return (record["status"] == "" and record["reason"] in _CHECK_REASONS
            and (record["policy"] == "" or (record["reason"] == "publication_policy_blocked"
                                            and record["policy"] in _CHECK_POLICIES)))


def _normal(value):
    return "\n".join(line.strip() for line in str(value or "").splitlines() if line.strip())


def _hash_text(value):
    return hashlib.sha256(_normal(value).encode("utf-8")).hexdigest()


def _hqz_presentation_text(text, origin, reference_url=None):
    """Remove only complete known publisher tails on a proven local post."""
    if origin in {"scheduled_autopost", _DUAL_COMIC_ORIGIN}:
        footers = (_AUTOMATIC_COMIC_FOOTER, _AUTOMATIC_CHARACTER_FOOTER)
    elif origin == _REPLACEMENT_ORIGIN:
        footers = (_REPLACEMENT_CHARACTER_FOOTER,)
    else:
        return text
    for footer in footers:
        suffix = "\n\n" + footer
        if not text.endswith(suffix):
            continue
        prefix = text[:-len(suffix)]
        # Older publishers inserted this exact operation-bound reference just
        # before the fixed footer. Do not infer it from the word 来源 in prose.
        reference_match = re.search(
            r"\n\n创作参考：(https://www\.xiaoheihe\.cn/app/bbs/link/[A-Za-z0-9_-]{1,64})$", prefix)
        if reference_match:
            if not isinstance(reference_url, str) or reference_match.group(1) != reference_url:
                # A citation-shaped fixed suffix without the operation-bound
                # URL is ambiguous: neither drop it nor send a partial tail.
                raise ValueError("source_text_unsupported")
            prefix = prefix[:reference_match.start()]
        return prefix if prefix.strip() else text
    return text


def _hqz_selection_hash(source):
    """Bind a decision to the complete source and exact outgoing presentation."""
    public_text, source_body, body = (source.get("public_text"), source.get("source_body"),
                                      source.get("body"))
    if (not all(isinstance(part, str) and part.strip() and "\x00" not in part
                for part in (public_text, source_body, body))):
        raise ValueError("source_text_unsupported")
    value = json.dumps([source_body, public_text, body], ensure_ascii=False, separators=(",", ":"))
    return hashlib.sha256(value.encode("utf-8")).hexdigest()


def _source_time(value):
    text = str(value)
    if not re.fullmatch(r"\d{10}(?:\.\d{1,6})?", text):
        raise ValueError("source_time_unavailable")
    result = float(text)
    if not 1_000_000_000 <= result < 10_000_000_000 or result > time.time():
        raise ValueError("source_time_unavailable")
    return result


def _hqz_resume_scope(host):
    """Require the same live incident generation throughout automatic sync."""
    scope = _SYNC_BARRIER.get()
    hooks = getattr(host, "_incident_hooks", None)
    if (not isinstance(scope, dict) or scope.get("host") is not host
            or hooks is None or scope.get("owner") is not hooks):
        raise ValueError("incident_barrier_unavailable")
    if hooks._blocked("heybox_qzone_sync", "qzone_publish"):
        raise ValueError("incident_feature_paused")
    current = hooks._resume_snapshot(("heybox_qzone_sync", "qzone_publish"))
    if current is None or current != scope.get("snapshot"):
        raise ValueError("incident_resume_barrier")
    return scope


def _hqz_resume_source_time(host, value):
    """Use the platform creation time, never this process's observation time."""
    scope = _hqz_resume_scope(host)
    try:
        stamp = _source_time(value)
    except ValueError:
        return None
    return stamp if math.floor(stamp) > math.floor(scope["snapshot"][0]) else None


def _qzone_picture_count(value):
    """Parse only an unambiguous nonnegative count, never a boolean."""
    if type(value) is int and value >= 0:
        return value
    if isinstance(value, str) and re.fullmatch(r"0|[1-9]\d{0,5}", value):
        return int(value)
    return None


def _qzone_image_refs(image):
    """Return exact image references for cross-checking; never fetch or log them."""
    if isinstance(image, dict):
        candidates = [image.get(key) for key in ("url2", "url3", "url1", "smallurl")]
    elif isinstance(image, str):
        candidates = [image]
    else:
        return set()
    refs = set()
    for value in candidates:
        if not isinstance(value, str) or not value or len(value) > 4096 or any(c.isspace() for c in value):
            continue
        try:
            parsed = urlsplit(value)
            if (parsed.scheme not in ("http", "https") or not parsed.hostname or parsed.username
                    or parsed.password or parsed.fragment or parsed.port not in (None, 80, 443)):
                continue
        except ValueError:
            continue
        refs.add(value)
    return refs


def _qzone_image_lists_agree(preview, full, expected):
    """Link a full response to the same ordered, nonempty detail preview."""
    if not isinstance(preview, list) or not 0 < len(preview) <= expected:
        return False
    if not isinstance(full, list) or len(full) != expected:
        return False
    refs = [_qzone_image_refs(image) for image in full]
    return (all(refs) and all(_qzone_image_refs(image) & refs[index]
                              for index, image in enumerate(preview)))


